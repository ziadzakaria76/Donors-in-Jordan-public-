/**
 * Write assets/js/img-manifest.js — which widths actually exist for each image.
 *
 * picture() in app.js used to emit a srcset for all four widths on every image,
 * and src for -1280.webp, whatever was on disk. Most of the brochure
 * photographs are only 480 px wide at source — they are phone pictures embedded
 * in a PDF, not studio files — so those pages asked the browser for
 * sherman2-interior-1-1280.webp and got a 404. Twenty-eight URLs, and on a wide
 * viewport the browser picks the largest candidate, so the gallery broke
 * exactly where the images are biggest.
 *
 * Upscaling is not the fix: 480 px is the real resolution. The fix is to
 * describe the image honestly and let the browser choose from what is there.
 *
 * Run after adding or re-rendering any image:
 *
 *   npm run manifest
 */

import { readdirSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const IMG = resolve(ROOT, "assets/img");
const OUT = resolve(ROOT, "assets/js/img-manifest.js");

const variants = {};
for (const file of readdirSync(IMG)) {
  const m = /^(.+)-(\d+)\.webp$/.exec(file);
  if (!m) continue;
  (variants[m[1]] ??= []).push(Number(m[2]));
}

const names = Object.keys(variants).sort();
for (const n of names) variants[n].sort((a, b) => a - b);

const body = names.map((n) => `  "${n}": [${variants[n].join(", ")}],`).join("\n");

writeFileSync(OUT, `/* Generated by tools/img-manifest.mjs — do not edit by hand.
   Run \`npm run manifest\` after adding or re-rendering an image.

   Which widths exist on disk for each image, so picture() can offer the
   browser a srcset it can actually fetch. A name missing from this map falls
   back to all four widths. */
const IMG_VARIANTS = {
${body}
};
`);

console.log(`  ✓ ${names.length} images → assets/js/img-manifest.js`);
const thin = names.filter((n) => Math.max(...variants[n]) < 800);
if (thin.length) console.log(`  note: ${thin.length} images top out below 800px — ${thin.join(", ")}`);
